document.addEventListener("DOMContentLoaded", function() {
    const observerOptions = {
        threshold: 0.1,
        rootMargin: "0px 0px -50px 0px" // I-bda l-effect qbel mat-wssal l-card nichan
    };

    // 2. Scroll Reveal Animation
    // Hada script bach l-elements ybano bchwya mli t-scrolli (fade in effect)
    const observer = new IntersectionObserver((entries) => {
        // Kan-7asbo ch7al men element ban f dqa
        let delay = 0;
        
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                // Ila kano bzaf dial l-3anassir (bhal cards), n-diro delay
                setTimeout(() => {
                    entry.target.classList.add("active");
                }, delay);
                
                delay += 150; // Zid 150ms l-kol element jdid
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    document.querySelectorAll(".reveal").forEach((el) => {
        observer.observe(el);
    });




    

    // 3. Statistics Counter Animation
    // Hada script bach l-ar9am dyal les statistiques ytla3o bzerba (Counting up)
    const statsObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const counters = entry.target.querySelectorAll('.stat-number');
                
                counters.forEach(counter => {
                    const target = +counter.getAttribute('data-target');
                    const suffix = counter.getAttribute('data-suffix') || '';
                    const duration = 2000; // 2 seconds
                    const frameDuration = 1000 / 60; // 60fps
                    const totalFrames = Math.round(duration / frameDuration);
                    
                    let frame = 0;
                    
                    const easeOutQuad = t => t * (2 - t);
                    
                    const updateCount = () => {
                        frame++;
                        const progress = easeOutQuad(frame / totalFrames);
                        const currentCount = Math.round(target * progress);
                        
                        if (frame < totalFrames) {
                            counter.innerText = currentCount + suffix;
                            requestAnimationFrame(updateCount);
                        } else {
                            counter.innerText = target + suffix;
                        }
                    };
                    
                    updateCount();
                });
                
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.5 });

    const statsSection = document.querySelector('.stats-container');
    if (statsSection) {
        statsObserver.observe(statsSection);
    }
});
